-- Это новая таблица. Существующая noise_data не меняется.
CREATE TABLE IF NOT EXISTS public.occupancy_data (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location text NOT NULL,
  occupied integer NOT NULL CHECK (occupied >= 0),
  total integer NOT NULL CHECK (total > 0 AND occupied <= total),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS occupancy_location_time_idx
  ON public.occupancy_data (location, created_at DESC);
ALTER TABLE public.occupancy_data ENABLE ROW LEVEL SECURITY;
